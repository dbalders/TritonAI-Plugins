// Captures the MCP tool catalog of an n8n instance into src/upstream-tools.ts, the pinned upstream
// contract that new tools are generated from and that tests hold every reviewed tool against.
//
// Point it at an instance running the n8n version being reviewed, authenticated with a bearer
// token that sees every tool (an instance-level MCP API key does; OAuth tokens only list the tools
// their scopes unlock):
//
//   N8N_MCP_URL=http://localhost:5678/mcp-server/http N8N_MCP_TOKEN=... N8N_VERSION=2.41.3 \
//     node scripts/capture-upstream-tools.mjs
import { spawnSync } from "node:child_process";
import * as Fs from "node:fs/promises";
import * as Path from "node:path";

const url = process.env.N8N_MCP_URL;
const token = process.env.N8N_MCP_TOKEN;
const version = process.env.N8N_VERSION;
if (!url || !token || !version || !/^\d+\.\d+\.\d+$/u.test(version)) {
  throw new Error("Set N8N_MCP_URL, N8N_MCP_TOKEN, and N8N_VERSION (for example 2.41.3).");
}

const PROTOCOL_VERSION = "2026-07-28";
let sequence = 0;
let session = null;

async function rpc(method, params = {}) {
  const headers = {
    accept: "application/json, text/event-stream",
    authorization: `Bearer ${token}`,
    "content-type": "application/json",
    "mcp-method": method,
    "mcp-protocol-version": PROTOCOL_VERSION,
  };
  if (session) headers["mcp-session-id"] = session;
  const response = await fetch(url, {
    method: "POST",
    headers,
    body: JSON.stringify({
      jsonrpc: "2.0",
      id: String(++sequence),
      method,
      params: {
        ...params,
        _meta: {
          "io.modelcontextprotocol/protocolVersion": PROTOCOL_VERSION,
          "io.modelcontextprotocol/clientCapabilities": {},
          "io.modelcontextprotocol/clientInfo": { name: "TritonAI n8n capture", version: "1.0.0" },
        },
      },
    }),
  });
  if (!response.ok) throw new Error(`${method} failed with HTTP ${response.status}.`);
  session = response.headers.get("mcp-session-id") ?? session;
  let text = await response.text();
  if (response.headers.get("content-type")?.includes("text/event-stream")) {
    text = text
      .split(/\r?\n/u)
      .filter((line) => line.startsWith("data:"))
      .map((line) => line.slice(5).trimStart())
      .join("\n");
  }
  const payload = JSON.parse(text);
  if (payload.error) throw new Error(`${method} failed: ${JSON.stringify(payload.error)}`);
  return payload.result;
}

function withoutSchemaDeclaration(schema) {
  const { $schema: _declaration, ...rest } = schema;
  return rest;
}

await rpc("server/discover");
const tools = [];
let cursor;
do {
  const page = await rpc("tools/list", cursor === undefined ? {} : { cursor });
  tools.push(...page.tools);
  cursor = page.nextCursor ?? undefined;
} while (cursor !== undefined);

const snapshot = tools
  .map((tool) => ({
    name: tool.name,
    title: tool.annotations?.title ?? tool.title ?? tool.name,
    annotations: {
      readOnlyHint: tool.annotations?.readOnlyHint === true,
      destructiveHint: tool.annotations?.destructiveHint === true,
      idempotentHint: tool.annotations?.idempotentHint === true,
      openWorldHint: tool.annotations?.openWorldHint === true,
    },
    inputSchema: withoutSchemaDeclaration(tool.inputSchema),
  }))
  .toSorted((left, right) => left.name.localeCompare(right.name));

const target = Path.resolve(import.meta.dirname, "..", "src", "upstream-tools.ts");
await Fs.writeFile(
  target,
  `// Generated by scripts/capture-upstream-tools.mjs from n8n ${version}. Do not edit by hand.
import type { UpstreamToolSnapshot } from "./upstream-schema.ts";

export const UPSTREAM_N8N_VERSION = "${version}";

export const UPSTREAM_TOOLS: ReadonlyArray<UpstreamToolSnapshot> = ${JSON.stringify(snapshot, null, 2)};
`,
);
const formatted = spawnSync("pnpm", ["exec", "vp", "fmt", target], { stdio: "inherit" });
if (formatted.status !== 0) throw new Error("Formatting the captured catalog failed.");
console.log(
  `captured ${snapshot.length} n8n ${version} tools into ${Path.relative(process.cwd(), target)}`,
);
